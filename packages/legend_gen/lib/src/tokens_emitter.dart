import 'package:dart_style/dart_style.dart';
import 'package:legend_gen/src/model.dart';
import 'package:legend_gen/src/version.dart';

/// Emits the generated token part file for all `@LegendTokenData` classes
/// of one source file (RFC-002 R5) — the mechanical members only:
///
/// - a `_$ClassName` mixin the class applies (`with _$ClassName`) carrying
///   `copyWith` and value `==`/`hashCode`,
/// - a private `_$ClassNameLerp` function the class's one-line
///   `static lerp` redirects to (statics cannot live on a mixin usefully,
///   and the public `ClassName.lerp` call sites must keep working).
///
/// The output is `part of` the token library: no imports of its own — the
/// source file's imports serve the whole library.
///
/// Lerpers by field type: `double` (guarded arithmetic, bit-identical to
/// `lerpDouble` incl. the a == b short-circuit), `Color.lerp`,
/// `TextStyle.lerp`, `BoxShadow.lerpList`; any other type `T` is assumed
/// to expose `static T lerp(T a, T b, double t)` — the convention nested
/// token classes satisfy by generation.
String emitTokensFile(List<TokenClass> classes) {
  assert(classes.isNotEmpty, 'emitTokensFile needs at least one class');
  final buffer = StringBuffer()
    ..writeln(
      '// GENERATED by legend_gen v$legendGenVersion — do not edit.\n'
      '// Source: ${classes.first.sourceBasename}\n'
      '// ignore_for_file: type=lint, unused_element',
    )
    ..writeln("part of '${classes.first.sourceBasename}';");

  for (final tokenClass in classes) {
    _emitTokenClass(buffer, tokenClass);
  }

  if (classes.any((c) => c.fields.any((f) => f.isList))) {
    buffer
      ..writeln()
      ..writeln('/// Element-wise list equality (lists compare by identity;')
      ..writeln('/// equal token sets must compare equal).')
      ..writeln(r'bool _$listEquals(List<Object?> a, List<Object?> b) {')
      ..writeln('if (identical(a, b)) return true;')
      ..writeln('if (a.length != b.length) return false;')
      ..writeln('for (var i = 0; i < a.length; i++) {')
      ..writeln('if (a[i] != b[i]) return false;')
      ..writeln('}')
      ..writeln('return true;')
      ..writeln('}');
  }

  return DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  ).format(buffer.toString());
}

void _emitTokenClass(StringBuffer b, TokenClass tokenClass) {
  final name = tokenClass.className;
  final mixinName = '_\$$name';
  final fields = tokenClass.fields;

  b
    ..writeln()
    ..writeln('/// Generated mechanical members for [$name] (RFC-002 R5):')
    ..writeln('/// `copyWith` and value `==`/`hashCode`. Applied via')
    ..writeln('/// `with $mixinName`; the abstract getters are implemented')
    ..writeln("/// by the class's own final fields.")
    ..writeln('mixin $mixinName {')
    ..writeln(fields.map((f) => '${f.type} get ${f.name};').join())
    ..writeln()
    ..writeln('/// Copy with the given fields replaced.')
    ..writeln('$name copyWith({')
    ..writeln(fields.map((f) => '${f.type}? ${f.name},').join())
    ..writeln('}) => $name(')
    ..writeln(
      fields.map((f) => '${f.name}: ${f.name} ?? this.${f.name},').join(),
    )
    ..writeln(');')
    ..writeln()
    ..writeln('@override')
    ..writeln('bool operator ==(Object other) =>')
    ..writeln('identical(this, other) ||')
    ..writeln('other is $name')
    ..writeln(fields.map((f) => '&& ${_equalsExpression(f)}').join())
    ..writeln(';')
    ..writeln()
    ..writeln('@override')
    ..writeln('int get hashCode => Object.hashAll([')
    ..writeln(
      fields
          .map((f) => f.isList ? 'Object.hashAll(${f.name}),' : '${f.name},')
          .join(),
    )
    ..writeln(']);')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Member-wise lerp for [$name]; the public [$name.lerp]')
    ..writeln('/// redirects here (part of the one token lerp a theme switch')
    ..writeln('/// pays, DESIGN.md §2.4).')
    ..writeln('$name ${mixinName}Lerp($name a, $name b, double t) => $name(')
    ..writeln(fields.map((f) => '${f.name}: ${_lerpExpression(f)},').join())
    ..writeln(');');
}

String _equalsExpression(TokenField f) {
  if (f.isList) return '_\$listEquals(other.${f.name}, ${f.name})';
  return 'other.${f.name} == ${f.name}';
}

String _lerpExpression(TokenField f) {
  final n = f.name;
  return switch (f.type) {
    // Guarded arithmetic — bit-identical to dart:ui lerpDouble (which a
    // part file cannot import): a == b returns a exactly, else the
    // weighted sum.
    'double' => 'a.$n == b.$n ? a.$n : a.$n * (1.0 - t) + b.$n * t',
    'Color' => 'Color.lerp(a.$n, b.$n, t)!',
    'TextStyle' => 'TextStyle.lerp(a.$n, b.$n, t)!',
    'List<BoxShadow>' => 'BoxShadow.lerpList(a.$n, b.$n, t)!',
    // Nested token classes: `static T lerp(T, T, double)` by convention.
    final type => '$type.lerp(a.$n, b.$n, t)',
  };
}
