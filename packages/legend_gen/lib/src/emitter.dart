import 'package:dart_style/dart_style.dart';
import 'package:legend_gen/src/model.dart';
import 'package:legend_gen/src/version.dart';

/// Emits the generated theme file for all themable widgets of one source
/// file (DESIGN.md §2.3): `XTheme`, `XThemeNullable`, `XThemeOverride`,
/// `XTheme.defaults(tokens)`, `merge`/`copyWith`/`lerp`, `XTheme.of`.
String emitThemeFile(List<ThemableWidget> widgets) {
  assert(widgets.isNotEmpty, 'emitThemeFile needs at least one widget');
  final buffer = StringBuffer()
    ..writeln('// GENERATED by legend_gen v$legendGenVersion — do not edit.')
    ..writeln('// Source: ${widgets.first.sourceBasename}')
    ..writeln('// ignore_for_file: type=lint, unused_import')
    ..writeln();

  final needsLerpDouble = widgets.any(
    (w) => w.fields.any((f) => f.lerp && f.resolvedType == 'double'),
  );
  final imports = <String>{
    if (needsLerpDouble) "import 'dart:ui' show lerpDouble;",
    "import 'package:flutter/widgets.dart';",
    "import 'package:legend_ui/legend_ui.dart';",
    // The source file itself — field types or defaultsTo helpers may be
    // declared right next to the widget (review C1).
    "import '${widgets.first.sourceBasename}';",
    ...widgets.first.sourceImports,
  }.toList()..sort();
  imports.forEach(buffer.writeln);

  for (final widget in widgets) {
    _emitWidget(buffer, widget);
  }
  return DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  ).format(buffer.toString());
}

void _emitWidget(StringBuffer b, ThemableWidget widget) {
  final theme = '${widget.className}Theme';
  final nullable = '${widget.className}ThemeNullable';
  final override = '${widget.className}ThemeOverride';
  final fields = widget.fields;

  // ── Resolved theme ────────────────────────────────────────────────
  b
    ..writeln()
    ..writeln('/// Resolved theme for [${widget.className}].')
    ..writeln('class $theme {')
    ..writeln('const $theme({')
    ..writeln(fields.map((f) => 'required this.${f.name},').join())
    ..writeln('});')
    ..writeln()
    ..writeln('/// Token-derived defaults (level 5).')
    ..writeln('factory $theme.defaults(LegendTokens t) => $theme(')
    ..writeln(fields.map((f) => '${f.name}: ${f.defaultsTo},').join())
    ..writeln(');')
    ..writeln()
    ..writeln(fields.map((f) => 'final ${f.resolvedType} ${f.name};').join());

  // of(): the five-level resolution chain (DESIGN.md §1 goal 3).
  b
    ..writeln()
    ..writeln('/// Resolves the theme: defaults <- app theme <- subtree')
    ..writeln('/// override <- constructor params ([local]).')
    ..writeln('static $theme of(BuildContext context, [$nullable? local]) {')
    ..writeln('final data = LegendTheme.of(context);')
    ..writeln('return $theme.defaults(data.tokens)')
    ..writeln('.merge(data.component<$nullable>())')
    ..writeln('.merge(LegendThemeOverride.maybeOf<$nullable>(context))')
    ..writeln('.merge(local);')
    ..writeln('}');

  b
    ..writeln()
    ..writeln('$theme merge($nullable? other) {')
    ..writeln('if (other == null) return this;')
    ..writeln('return $theme(')
    ..writeln(
      fields.map((f) => '${f.name}: other.${f.name} ?? ${f.name},').join(),
    )
    ..writeln(');')
    ..writeln('}');

  b
    ..writeln()
    ..writeln('$theme copyWith({')
    ..writeln(fields.map((f) => '${f.type} ${f.name},').join())
    ..writeln('}) => $theme(')
    ..writeln(
      fields.map((f) => '${f.name}: ${f.name} ?? this.${f.name},').join(),
    )
    ..writeln(');');

  b
    ..writeln()
    ..writeln('static $theme lerp($theme a, $theme b, double t) => $theme(')
    ..writeln(fields.map((f) => '${f.name}: ${_lerpExpression(f)},').join())
    ..writeln(');')
    ..writeln('}');

  // ── Sparse theme (levels 1–3) ─────────────────────────────────────
  b
    ..writeln()
    ..writeln('/// Sparse overrides for [$theme]; null means "inherit".')
    ..writeln('class $nullable {')
    ..writeln('const $nullable({')
    ..writeln(fields.map((f) => 'this.${f.name},').join())
    ..writeln('});')
    ..writeln()
    ..writeln(fields.map((f) => 'final ${f.type} ${f.name};').join())
    ..writeln()
    ..writeln('$nullable merge($nullable? other) {')
    ..writeln('if (other == null) return this;')
    ..writeln('return $nullable(')
    ..writeln(
      fields.map((f) => '${f.name}: other.${f.name} ?? ${f.name},').join(),
    )
    ..writeln(');')
    ..writeln('}')
    ..writeln('}');

  // ── Subtree override widget (level 2) ─────────────────────────────
  b
    ..writeln()
    ..writeln('/// Overrides [$theme] for a subtree (level 2).')
    ..writeln('class $override extends StatelessWidget {')
    ..writeln('const $override({')
    ..writeln('required this.data, required this.child, super.key,')
    ..writeln('});')
    ..writeln()
    ..writeln('final $nullable data;')
    ..writeln('final Widget child;')
    ..writeln()
    ..writeln('@override')
    ..writeln('Widget build(BuildContext context) =>')
    ..writeln('LegendThemeOverride<$nullable>(data: data, child: child);')
    ..writeln('}');
}

String _lerpExpression(ThemedField f) {
  final n = f.name;
  if (!f.lerp) return 't < 0.5 ? a.$n : b.$n';
  return switch (f.resolvedType) {
    'double' => 'lerpDouble(a.$n, b.$n, t)!',
    'Color' => 'Color.lerp(a.$n, b.$n, t)!',
    'EdgeInsets' || 'EdgeInsetsGeometry' =>
      'EdgeInsetsGeometry.lerp(a.$n, b.$n, t)! as ${f.resolvedType}',
    'BorderRadius' => 'BorderRadius.lerp(a.$n, b.$n, t)!',
    'TextStyle' => 'TextStyle.lerp(a.$n, b.$n, t)!',
    _ => 't < 0.5 ? a.$n : b.$n',
  };
}
