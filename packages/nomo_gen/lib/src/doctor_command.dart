import 'dart:io';

import 'package:nomo_gen/src/emitter.dart';
import 'package:nomo_gen/src/model.dart';
import 'package:nomo_gen/src/parser.dart';
import 'package:nomo_gen/src/version.dart';
import 'package:path/path.dart' as p;

const _generatedSuffix = '.theme.g.dart';

/// How much a [DoctorFinding] matters; both count as problems (exit 1).
enum DoctorSeverity { error, warning }

/// One `nomo_gen doctor` finding: a located diagnostic plus a severity.
class DoctorFinding {
  const DoctorFinding(this.severity, this.diagnostic);

  final DoctorSeverity severity;
  final NomoGenDiagnostic diagnostic;

  @override
  String toString() =>
      '${severity.name}: ${diagnostic.path}:${diagnostic.line} '
      '${diagnostic.message}';
}

/// Runs `nomo_gen doctor`: validates the theme setup under [paths] and
/// prints one `severity: path:line message` line per finding
/// (DESIGN.md §5.3 "a `doctor` for mis-registered themes").
///
/// Checked, in order:
///
/// - a `@NomoThemeable` widget whose `.theme.g.dart` is missing,
/// - stale generated output (re-emit and diff, like `themes --check`),
/// - orphaned `*.theme.g.dart` whose source is gone or no longer
///   `@NomoThemeable`,
/// - a generated file stamped by a different nomo_gen version (warning),
///
/// plus any decorator-contract violation the parser reports.
///
/// Returns 1 when anything was found (warnings included), else 0 after
/// printing `no problems found`.
Future<int> runDoctor(List<String> paths) async {
  final findings = collectDoctorFindings(paths);
  findings.forEach(stdout.writeln);
  if (findings.isEmpty) {
    stdout.writeln('no problems found');
    return 0;
  }
  stdout.writeln('${findings.length} problem(s) found');
  return 1;
}

/// The pure core of [runDoctor]: collects findings without printing.
List<DoctorFinding> collectDoctorFindings(List<String> paths) {
  final findings = <DoctorFinding>[];
  void error(String path, int line, String message) => findings.add(
    DoctorFinding(DoctorSeverity.error, NomoGenDiagnostic(path, line, message)),
  );
  void warning(String path, int line, String message) => findings.add(
    DoctorFinding(
      DoctorSeverity.warning,
      NomoGenDiagnostic(path, line, message),
    ),
  );

  final sources = <File>[];
  final generated = <File>[];
  for (final path in paths) {
    for (final file in _dartFilesIn(path)) {
      if (file.path.endsWith(_generatedSuffix)) {
        generated.add(file);
      } else if (!file.path.endsWith('.g.dart')) {
        sources.add(file);
      }
    }
  }

  // One parse per source file; null marks a decorator-contract violation
  // (reported once as error findings, right here).
  final parsed = <String, List<ThemableWidget>?>{};
  List<ThemableWidget>? widgetsOf(String sourcePath) {
    return parsed.putIfAbsent(sourcePath, () {
      try {
        return parseThemableWidgets(
          sourcePath,
          File(sourcePath).readAsStringSync(),
        );
      } on NomoGenException catch (e) {
        for (final d in e.diagnostics) {
          error(d.path, d.line, d.message);
        }
        return null;
      }
    });
  }

  // (a) missing generated file, (b) stale generated output.
  for (final file in sources) {
    final widgets = widgetsOf(file.path);
    if (widgets == null || widgets.isEmpty) continue;
    final outputPath =
        '${file.path.substring(0, file.path.length - '.dart'.length)}'
        '$_generatedSuffix';
    final outputFile = File(outputPath);
    if (!outputFile.existsSync()) {
      error(
        file.path,
        widgets.first.line,
        '@NomoThemeable "${widgets.first.className}" has no generated '
        'theme file — run `nomo_gen themes`.',
      );
    } else if (outputFile.readAsStringSync() != emitThemeFile(widgets)) {
      error(outputPath, 1, 'stale generated output — run `nomo_gen themes`.');
    }
  }

  // (c) orphaned generated files, (d) generator version drift.
  for (final file in generated) {
    final sourcePath =
        '${file.path.substring(0, file.path.length - _generatedSuffix.length)}'
        '.dart';
    if (!File(sourcePath).existsSync()) {
      error(
        file.path,
        1,
        'orphaned generated file — ${p.basename(sourcePath)} is gone; '
        'delete it.',
      );
    } else {
      final widgets = widgetsOf(sourcePath);
      if (widgets != null && widgets.isEmpty) {
        error(
          file.path,
          1,
          'orphaned generated file — ${p.basename(sourcePath)} has no '
          '@NomoThemeable widget; delete it or restore the annotation.',
        );
      }
    }

    final lines = file.readAsLinesSync();
    final header = lines.isEmpty ? '' : lines.first;
    final stamped = RegExp(
      r'GENERATED by nomo_gen v(\S+)',
    ).firstMatch(header)?.group(1);
    if (stamped != null && stamped != nomoGenVersion) {
      warning(
        file.path,
        1,
        'generated by nomo_gen v$stamped, current is v$nomoGenVersion — '
        'rerun `nomo_gen themes`.',
      );
    }
  }

  return findings;
}

List<File> _dartFilesIn(String path) {
  final entity = FileSystemEntity.typeSync(path);
  if (entity == FileSystemEntityType.file) return [File(path)];
  if (entity != FileSystemEntityType.directory) {
    stderr.writeln('WARNING: $path does not exist, skipping');
    return const [];
  }
  return Directory(path)
      .listSync(recursive: true)
      .whereType<File>()
      .where(
        (f) =>
            f.path.endsWith('.dart') && !p.split(f.path).contains('.dart_tool'),
      )
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));
}
